"""Writing digest pages into the RC vault as Obsidian notes."""

from __future__ import annotations

import os
import re
from datetime import date, datetime
from pathlib import Path

from crier.digest import SectionResult

NOW_PAGE = "zulip-now.md"
CREATED = re.compile(r"^created:\s*(\d{4}-\d{2}-\d{2})\s*$", re.MULTILINE)


def day_page_name(day: date) -> str:
    # Not plain YYYY-MM-DD.md: the RC vault's daily notes already use that name.
    return f"zulip-{day.isoformat()}.md"


def existing_created(path: Path) -> str | None:
    """A page's `created:` date, kept across rewrites."""
    try:
        head = path.read_text(encoding="utf-8")[:500]
    except FileNotFoundError:
        return None
    m = CREATED.search(head)
    return m.group(1) if m else None


def frontmatter(created: str, modified: str) -> str:
    return (
        "---\n"
        f"created: {created}\n"
        f"modified: {modified}\n"
        "type: reference\n"
        "tags: [rc/zulip, status/processed]\n"
        "status: processed\n"
        "kind: digest\n"
        "---\n"
    )


def page(title: str, stamp: str, results: list[SectionResult]) -> str:
    parts = [f"# {title}\n", f"_{stamp}_\n"]
    for r in results:
        parts.append(f"## {r.spec.title}\n\n{r.body}\n")
    if not results:
        parts.append("_No channels configured for this page._\n")
    return "\n".join(parts)


def now_page(results: list[SectionResult], now: datetime) -> str:
    total = sum(r.messages for r in results)
    stamp = (
        f"Updated {now:%a %H:%M} by crier from {total} messages. "
        f"Today's digest: [[{day_page_name(now.date())[:-3]}]]. "
        "Generated by a model: open the ↗ links before you trust a detail."
    )
    return page("At the hub right now", stamp, results)


def day_page(results: list[SectionResult], day: date, now: datetime) -> str:
    total = sum(r.messages for r in results)
    stamp = (
        f"Updated {now:%a %H:%M} by crier from {total} messages. "
        "Generated by a model: open the ↗ links before you trust a detail."
    )
    return page(f"Zulip, {day:%a %d %b %Y}", stamp, results)


def write_page(path: Path, body: str, today: date) -> None:
    """Write a page atomically, keeping its original `created:` date."""
    path.parent.mkdir(parents=True, exist_ok=True)
    created = existing_created(path) or today.isoformat()
    text = frontmatter(created, today.isoformat()) + "\n" + body
    tmp = path.with_name(f".{path.name}.tmp")  # dot-prefixed so Obsidian ignores it
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)
